#!/usr/bin/env node

/**
 * Gerador de snapshot: extrai records C# de REQUEST, com a nulabilidade de cada campo, e persiste
 * em JSON versionado.
 *
 * D83 (v1.11.0a8b69), estendida ao gate de campos de request na v1.11.0a8b72 (NO-4, NO-17): o gate
 * `gate-contract-request-fields.mjs` lê este snapshot, e não `../New project 3`, em tempo de execução.
 * O CI não tem o backend. O snapshot de response (`backend-response-records.snapshot.json`) não serve
 * aqui porque não registra nulabilidade, e é ela que separa DEFAULT_SILENCIOSO de LACUNA/NAO_ENVIADO.
 *
 * Por que existe: o markdown do contrato (`docs/BACKEND-ESTADO-ATUAL-E-CONTRATO.md:2789`, 2026-08-12)
 * traz `MapeamentoCfopRequest(Ambito, CfopCodigo)`, sem `TipoItem` (NO-4). O C# tem 3 campos.
 *
 * Uso: node scripts/generate-backend-request-records-snapshot.mjs
 * Saída: scripts/backend-request-records.snapshot.json (versionado, commitado; não se edita à mão)
 */

import fs from 'fs';
import path from 'path';
import { spawnSync } from 'child_process';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const BACKEND_ROOT = path.resolve(path.dirname(ROOT), 'New project 3');
const SNAPSHOT_PATH = path.join(ROOT, 'scripts', 'backend-request-records.snapshot.json');

/** Record C# → diretório (relativo à raiz do backend) onde ele é declarado. */
const RECORDS_TO_EXTRACT = {
  CriarNaturezaOperacaoRequest: { module: 'naturezasOperacao', dir: 'src/Erp.Application/Fiscal/Cadastros/NaturezaOperacao' },
  AtualizarNaturezaOperacaoRequest: { module: 'naturezasOperacao', dir: 'src/Erp.Application/Fiscal/Cadastros/NaturezaOperacao' },
  InativarNaturezaOperacaoRequest: { module: 'naturezasOperacao', dir: 'src/Erp.Application/Fiscal/Cadastros/NaturezaOperacao' },
  MapeamentoCfopRequest: { module: 'naturezasOperacao', dir: 'src/Erp.Application/Fiscal/Cadastros/NaturezaOperacao' }
};

/** Divide a lista de parâmetros por vírgula de nível zero (ignora vírgulas dentro de <>, () e []). */
function dividirParametros(bloco) {
  const partes = [];
  let profundidade = 0;
  let atual = '';
  for (const ch of bloco) {
    if (ch === '<' || ch === '(' || ch === '[') profundidade++;
    if (ch === '>' || ch === ')' || ch === ']') profundidade--;
    if (ch === ',' && profundidade === 0) {
      partes.push(atual);
      atual = '';
      continue;
    }
    atual += ch;
  }
  if (atual.trim()) partes.push(atual);
  return partes;
}

/** Extrai { name, nullable, csharpType } de cada parâmetro do construtor primário do record. */
function extrairCampos(texto, recordName) {
  const decl = new RegExp(`record\\s+${recordName}\\s*\\(`);
  const m = decl.exec(texto);
  if (!m) return null;

  const abre = m.index + m[0].length - 1;
  let fecha = abre + 1;
  let nivel = 1;
  while (fecha < texto.length && nivel > 0) {
    if (texto[fecha] === '(') nivel++;
    else if (texto[fecha] === ')') nivel--;
    if (nivel > 0) fecha++;
  }
  if (nivel !== 0) return null;

  const bloco = texto
    .substring(abre + 1, fecha)
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .split('\n')
    .map((linha) => linha.replace(/\/\/.*$/, ''))
    .join('\n');

  const campos = [];
  for (const parametro of dividirParametros(bloco)) {
    const semAtributo = parametro.replace(/\[[^\]]*\]/g, ' ');
    const semDefault = semAtributo.replace(/=[\s\S]*$/, '').trim();
    const tokens = semDefault.split(/\s+/).filter(Boolean);
    if (tokens.length < 2) continue;
    const nome = tokens[tokens.length - 1];
    const tipo = tokens.slice(0, -1).join(' ');
    if (!/^[A-Z][A-Za-z0-9]*$/.test(nome)) {
      throw new Error(`Parâmetro não reconhecido em ${recordName}: "${parametro.trim()}"`);
    }
    campos.push({
      name: nome.charAt(0).toLowerCase() + nome.slice(1),
      nullable: tipo.endsWith('?'),
      csharpType: tipo
    });
  }

  return { campos, linha: texto.substring(0, m.index).split('\n').length };
}

function commitDoBackend() {
  const r = spawnSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: BACKEND_ROOT, encoding: 'utf8' });
  return r.status === 0 ? r.stdout.trim() : null;
}

function gerar() {
  if (!fs.existsSync(BACKEND_ROOT)) {
    console.error(`❌ Backend não encontrado em ${BACKEND_ROOT}. O snapshot só é gerado na máquina que tem o backend.`);
    process.exit(1);
  }

  const snapshot = {
    generatedAt: new Date().toISOString(),
    source: 'Generated by scripts/generate-backend-request-records-snapshot.mjs',
    backendCommit: commitDoBackend(),
    records: {}
  };
  const falhas = [];

  for (const [recordName, { module, dir }] of Object.entries(RECORDS_TO_EXTRACT)) {
    const diretorio = path.join(BACKEND_ROOT, dir);
    let achado = null;
    if (fs.existsSync(diretorio)) {
      for (const arquivo of fs.readdirSync(diretorio).filter((f) => f.endsWith('.cs')).sort()) {
        const texto = fs.readFileSync(path.join(diretorio, arquivo), 'utf8');
        const r = extrairCampos(texto, recordName);
        if (r && r.campos.length > 0) {
          achado = { ...r, arquivo: `${dir}/${arquivo}` };
          break;
        }
      }
    }
    if (!achado) {
      falhas.push(recordName);
      console.warn(`⚠️  ${recordName}: não encontrado em ${dir}`);
      continue;
    }
    snapshot.records[recordName] = {
      module,
      fields: achado.campos,
      origin: { file: achado.arquivo, line: achado.linha }
    };
    console.log(`✅ ${recordName}: ${achado.campos.length} campos de ${achado.arquivo}:${achado.linha}`);
  }

  if (falhas.length > 0) {
    console.error(`\n❌ ${falhas.length} record(s) não encontrado(s): ${falhas.join(', ')}`);
    console.error('Não é possível gerar snapshot incompleto.');
    process.exit(1);
  }

  // Campo que some de um record já registrado é regressão mascarada: reprova, como no gerador de response.
  if (fs.existsSync(SNAPSHOT_PATH)) {
    const anterior = JSON.parse(fs.readFileSync(SNAPSHOT_PATH, 'utf8'));
    const perdas = [];
    for (const [recordName, novo] of Object.entries(snapshot.records)) {
      const antigo = anterior.records?.[recordName];
      if (!antigo) continue;
      const nomesNovos = new Set(novo.fields.map((f) => f.name));
      const faltam = antigo.fields.map((f) => f.name).filter((n) => !nomesNovos.has(n));
      if (faltam.length > 0) perdas.push(`${recordName}: faltam ${faltam.join(', ')}`);
    }
    if (perdas.length > 0) {
      console.error('\n❌ REGRESSÃO — campos perdidos em records já registrados:');
      for (const p of perdas) console.error(`   ${p}`);
      process.exit(1);
    }
  }

  fs.writeFileSync(SNAPSHOT_PATH, `${JSON.stringify(snapshot, null, 2)}\n`);
  console.log(`\n✅ Snapshot gerado: ${SNAPSHOT_PATH} (backend ${snapshot.backendCommit ?? '?'})`);
}

try {
  gerar();
} catch (e) {
  console.error('❌ Erro ao gerar snapshot:', e.message);
  process.exit(1);
}
